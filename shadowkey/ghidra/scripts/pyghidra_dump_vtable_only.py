"""
Decompile every function that is reachable ONLY through a data-section
pointer (a vtable slot or a handler table) and that Ghidra's auto-analysis
therefore never turned into a function.

Why this exists: `decomp_all.c` holds 2006 functions, and "every *called*
address is defined" -- but a virtual function nothing calls directly has no
`bl` pointing at it, so it is not in the dump at all. Scanning the data
section for words that point into the code and are not a decompiled
function start finds ~640 of them (114 bare `bx lr` stubs, ~526 real ones,
about 10 KB of code). Among them: the player's turn/look slots
(0x1001f364..0x1001f530), the standing Height() (0x10006230), the extra
move slots after FUN_100065b4, and the creature walk (0x10086d3c).

Run from repo root:
  python shadowkey/ghidra/scripts/pyghidra_dump_vtable_only.py

Writes shadowkey/extracted/decomp_vtable_only.c in decomp_all.c's own
`// ==== <addr> <name> ====` framing, each entry followed by the data
addresses that point at it. Does not save the program.
"""
import os
import re
import struct
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]

import pyghidra  # noqa: E402

GHIDRA_INSTALL_DIR = Path(os.environ.get(
    "GHIDRA_INSTALL_DIR", r"C:\Users\Admin\Desktop\tools\ghidra_12.0.4_PUBLIC"))
PROJECT_DIR = REPO_ROOT / "shadowkey" / "ghidra"
EXTRACTED = REPO_ROOT / "shadowkey" / "extracted"
OUT = EXTRACTED / "decomp_vtable_only.c"

BASE = 0x10000000
DATA_START = 0x100A6000  # first address past the code; strings and vtables follow

blob = (EXTRACTED / "6r51_code.bin").read_bytes()
known = sorted(int(m, 16) for m in re.findall(
    rb"// ==== ([0-9a-f]{8}) ", (EXTRACTED / "decomp_all.c").read_bytes()))
known_set = set(known)
code_end = known[-1] + 0x400

targets = {}
for off in range(DATA_START - BASE, len(blob) - 3, 4):
    w = struct.unpack_from("<I", blob, off)[0]
    if BASE <= w < code_end and w % 4 == 0 and w not in known_set:
        targets.setdefault(w, []).append(BASE + off)

print(f"{len(targets)} data-referenced code addresses outside decomp_all.c")

pyghidra.start(install_dir=GHIDRA_INSTALL_DIR)

with pyghidra.open_program(
    binary_path=None,
    project_location=str(PROJECT_DIR),
    project_name="ShadowkeyProject",
    program_name="6r51_code.bin",
    analyze=False,
    nested_project_location=False,
) as flat_api:
    program = flat_api.getCurrentProgram()
    space = program.getAddressFactory().getDefaultAddressSpace()
    listing = program.getListing()

    from ghidra.app.decompiler import DecompInterface
    decomp = DecompInterface()
    decomp.openProgram(program)

    done = failed = skipped = 0
    with OUT.open("w", encoding="utf-8", newline="\n") as out:
        out.write("// Functions reachable only through data pointers (vtables,\n"
                  "// handler tables). Generated by pyghidra_dump_vtable_only.py.\n\n")
        for t in sorted(targets):
            addr = space.getAddress(t)
            func = flat_api.getFunctionAt(addr)
            if func is None:
                # A pointer into the *middle* of an existing function is a
                # jump-table arm or a literal, not a function of its own.
                container = flat_api.getFunctionContaining(addr)
                if container is not None:
                    skipped += 1
                    continue
                if listing.getInstructionAt(addr) is None:
                    flat_api.disassemble(addr)
                try:
                    func = flat_api.createFunction(addr, f"VFUN_{t:08x}")
                except Exception:  # noqa: BLE001
                    func = None
            refs = ", ".join(f"{r:08x}" for r in targets[t][:12])
            more = "" if len(targets[t]) <= 12 else f" (+{len(targets[t]) - 12} more)"
            if func is None:
                out.write(f"// ==== {t:08x} (no function could be created) ====\n"
                          f"// referenced from: {refs}{more}\n\n")
                failed += 1
                continue
            res = decomp.decompileFunction(func, 60, None)
            out.write(f"// ==== {t:08x} {func.getName()} ====\n"
                      f"// referenced from: {refs}{more}\n")
            if res.decompileCompleted():
                out.write(res.getDecompiledFunction().getC())
                done += 1
            else:
                out.write("// (decompilation failed)\n")
                failed += 1
            out.write("\n")
    print(f"decompiled {done}, failed {failed}, mid-function pointers skipped {skipped}")
    print("wrote", OUT)
    # Leave the project as it was found: this is a read-only dump.
    program.undo() if program.canUndo() else None
